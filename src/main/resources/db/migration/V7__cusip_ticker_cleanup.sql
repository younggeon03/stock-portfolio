-- CUSIP → 티커 변환 결과 중 잘못 고른 것을 지운다 (2026-10-03).
-- 지우면 다음 13F 배치(매일 07:00)가 "아직 모르는 CUSIP" 으로 보고 고친 규칙으로 다시 묻는다.
--
-- 1. 채권·워런트 이름이 티커 자리에 들어간 것 ("AKAM 0.125 05.01.25"). 공백이 있다
-- 2. 미국 거래소 결과가 없을 때 첫 결과를 그대로 쓴 것
--    - 통합 코드의 달러 표기 ("CCL1USD", "ACCDUSD")
--    - 다른 나라 거래소 코드 ("AVU0", "AM6"). 미국 티커는 숫자로 끝나지 않는다
-- 정상 티커가 섞여 지워져도 다시 물으면 같은 값이 돌아오므로 손해는 한 번 더 묻는 것뿐이다.
DELETE FROM cusip_ticker
 WHERE ticker LIKE '% %'
    OR ticker LIKE '%USD'
    OR ticker REGEXP '[0-9]$';
